"""Write sharedness_results.tex (input by sharedness_model.tex) from the CSVs of
notebook 04, so the numbers in the document are exactly the notebook's.

    .venv/Scripts/python.exe notebooks_sharedness/_results_tex.py
"""
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
RES = HERE / "results"
OUT = HERE.parent / "sharedness_results.tex"

ARM_SYN = ["before", "multistart-pca", "multistart", "two-stage", "switch, calibrated slab"]
NAME_SYN = {"before": "before (1 start, 400 sweeps)", "multistart-pca": "multi-start, PCA start",
            "multistart": "multi-start, gCCA start", "two-stage": "two-stage (final)",
            "switch, calibrated slab": "view switch, calibrated slab"}
ARM_COH = ["before: current q, fixed pi=0.5", "before: current q, learned pi",
           "paired q, learned pi (notebook 01)", "after: scale-free paired, learned pi",
           "after: + reference cohort"]
NAME_COH = {ARM_COH[0]: r"CohortFACTM, $\pi=0.5$ fixed", ARM_COH[1]: r"CohortFACTM, $\pi$ learned",
            ARM_COH[2]: r"\textbf{paired, $\pi$ learned (final)}", ARM_COH[3]: "scale-free paired (V1)",
            ARM_COH[4]: "reference cohort (V2)"}


def f(x, d=3):
    return "--" if pd.isna(x) else f"{x:.{d}f}"


lines = [r"% generated by notebooks_sharedness/_results_tex.py -- do not edit by hand"]

s = pd.read_csv(RES / "improve_synthetic.csv")
g = s.groupby(["level", "arm"]).mean(numeric_only=True)
lines += [r"\paragraph{Synthetic data (5 seeds per level).} Factor recovery is the Hungarian-matched $|\mathrm{corr}|$ "
          r"with the true factors; ``strong'' excludes the deliberately weak factor of the hard level. Pattern "
          r"recovery compares the called pattern ($a_{mk}\ge0.1$, or the frozen $\hat H$, or $\E h>0.5$) with $H$.",
          r"\begin{center}\footnotesize\setlength{\tabcolsep}{4pt}\begin{tabular}{@{}llrrrrr@{}}\toprule",
          r"level & arm & mean $|$corr$|$ & worst strong & worst (all) & cells correct & exact columns\\\midrule"]
for lv in ["easy", "hard"]:
    K = 4 if lv == "easy" else 6
    for a in ARM_SYN:
        r = g.loc[(lv, a)]
        lines.append(f"{lv} & {NAME_SYN[a]} & {f(r.mean_corr)} & {f(r.min_corr_strong)} & {f(r.min_corr)} & "
                     f"{f(r.cell_acc)} & {f(r.exact_cols, 1)}/{K}\\\\")
    if lv == "easy":
        lines.append(r"\midrule")
lines += [r"\bottomrule\end{tabular}\end{center}"]
sw = s[s.arm == "switch, calibrated slab"].groupby("level")[["on_share", "switch_auc"]].mean()
lines += [rf"The calibrated view switch has {100*sw.loc['easy','on_share']:.1f}\% / {100*sw.loc['hard','on_share']:.1f}\% "
          rf"of switches on (truth $50\%$) and switch AUC {f(sw.loc['easy','switch_auc'],2)} / {f(sw.loc['hard','switch_auc'],2)} "
          r"(easy / hard). Refinement flipped "
          rf"{s[s.arm=='two-stage'].flips.mean():.1f} cells on average."]

c = pd.read_csv(RES / "improve_cohort.csv")
gc = c.groupby(["level", "arm"]).mean(numeric_only=True)
lines += [r"\paragraph{Cohort prior (3 seeds $\times$ true rates $0.1,0.3,0.6$, $C=6$).} $\gamma$ AUC: ranking of $\E\gamma$ "
          r"against the true switches; null/alt: mean $\E\gamma$ where the truth is $0$/$1$.",
          r"\begin{center}\footnotesize\setlength{\tabcolsep}{4pt}\begin{tabular}{@{}llrrrr@{}}\toprule",
          r"level & arm & $|\E\pi-\pi^\ast|$ & $\gamma$ AUC & null $\E\gamma$ & alt $\E\gamma$\\\midrule"]
for lv in ["easy", "hard"]:
    for a in ARM_COH:
        r = gc.loc[(lv, a)]
        lines.append(f"{lv} & {NAME_COH[a]} & {f(r.pi_err)} & {f(r.gamma_auc)} & {f(r.null_gamma)} & {f(r.alt_gamma)}\\\\")
    if lv == "easy":
        lines.append(r"\midrule")
lines += [r"\bottomrule\end{tabular}\end{center}",
          r"The reference arm is scored against shifts relative to the reference cohort (different truth)."]

if (RES / "improve_real.csv").exists():
    rl = pd.read_csv(RES / "improve_real.csv")
    lines += [r"\paragraph{Real data (3 seeds; 4 starts).} Stability across seeds: correlation of the activity matrices "
              r"and Hungarian-matched factor correlation (mean, and mean of the worst factor).",
              r"\begin{center}\footnotesize\setlength{\tabcolsep}{4pt}\begin{tabular}{@{}llrrr@{}}\toprule",
              r"data & arm & activity corr & mean factor match & worst factor match\\\midrule"]
    for _, r in rl.iterrows():
        lines.append(f"{r.dataset} & {r.arm} & {f(r.activity_corr)} & {f(r.mean_factor_match)} & {f(r.min_factor_match)}\\\\")
    lines += [r"\bottomrule\end{tabular}\end{center}"]
if (RES / "improve_real_cohort.csv").exists():
    rc = pd.read_csv(RES / "improve_real_cohort.csv")
    lines += [r"\begin{center}\footnotesize\setlength{\tabcolsep}{4pt}\begin{tabular}{@{}llrrr@{}}\toprule",
              r"data & cohort prior & $\E\pi$ & switches on ($>0.9$) & switches off ($<0.1$)\\\midrule"]
    for _, r in rc.iterrows():
        lines.append(f"{r.dataset} & {NAME_COH.get(r.arm, r.arm)} & {f(r.E_pi,2)} $\\pm$ {f(r.sd_pi,2)} & "
                     f"{100*r.frac_on:.0f}\\% & {100*r.frac_off:.0f}\\%\\\\")
    lines += [r"\bottomrule\end{tabular}\end{center}"]

OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print("wrote", OUT)
